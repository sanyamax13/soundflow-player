package main

import "log"

// onTrackAdded — программа сама скачала новую песню: положить её в план телефона и проверить,
// есть ли у неё обложка (coverkeeper.go — найдёт, если нет).
func (s *Service) onTrackAdded(trackID string) {
	s.autoPlanAdd(trackID)
	s.covers.Kick()
	s.genres.Kick()
	s.origCovers.Kick()
	s.waveforms.Kick()
	s.bass.Kick()
	s.loudness.Kick() // и громкость для выравнивания (loudkeeper.go)
	s.moods.Kick() // и настроение/жанр (moodkeeper.go)
	s.spectrum.Kick()
}

// Новая скачанная песня сама ложится в план «живого» телефона (Alex TG 20159:
// «учи программу всему, чтобы она была автономной»; TG 20158/20167: телефон только
// ПРЕДЛАГАЕТ «Скачать», не качает без спроса). Раньше песню, скачанную на компьютер
// по запросу из плеера или из окна, нужно было вручную добавлять на телефон — и
// «ничего не попадало на телефон».
//
// Сюда попадают только песни, которые программа СКАЧАЛА сама (запрос из плеера,
// «Найти трек» в окне, «Скачать выбранные» в «Открытиях», замена плохой версии).
// Песни, которые скан нашёл в папке, в план не кладутся: их могут быть тысячи,
// а решать про них должен Alex (меню «Добавить на телефон», список с галочками).
//
// План дополняется (MergePlan), а не заменяется. Устройства нет (телефон ещё ни
// разу не заходил) — тихо ничего не делаем.
func (s *Service) autoPlanAdd(trackID string) {
	if trackID == "" || s.db == nil {
		return
	}
	dev, _, _, ok, err := s.db.LatestDevice()
	if err != nil || !ok {
		return
	}
	if _, _, err := s.db.MergePlan(dev, []string{trackID}, nil); err != nil {
		log.Printf("автоплан: не смог добавить %s в план телефона: %v", trackID, err)
	}
}
