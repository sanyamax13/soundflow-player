/// Адрес сервера. По умолчанию — реальный сервер в домашней сети (fg),
/// потому что собираем в основном для настоящего телефона Alex, не для
/// эмулятора. Для эмулятора адрес этого компьютера — 10.0.2.2, передать
/// через --dart-define=SOUNDFLOW_API=http://10.0.2.2:8090 (см. README).
/// Позже вынесем в настройки; пока одно место.
const String apiBaseUrl = String.fromEnvironment(
  'SOUNDFLOW_API',
  defaultValue: 'http://192.168.1.73:8090',
);

/// Обложка прямо из файла трека на сервере (см. `GET /v1/cover/{id}` —
/// 05.09.2026). Нужна как сетевой запасной вариант там, где нет локально
/// скачанной обложки: у старой перенесённой библиотеки `cover_url` из
/// каталога пуст (его искали только для новых треков через Яндекс), а тут
/// сервер сам достаёт картинку, если она зашита в сам mp3-файл. Нет
/// картинки в файле — сервер ответит 404, экран уже умеет откатываться на
/// серый плейсхолдер.
String coverUrlFor(String trackId) => '$apiBaseUrl/v1/cover/$trackId';
