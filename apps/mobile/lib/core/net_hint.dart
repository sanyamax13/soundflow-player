import 'notice.dart';

/// Единая подсказка для всех мест «сервер не ответил» (Опус-ревью телефона
/// 14.09.2026, пункт 1): раньше ошибка была тупиком — без причины и без
/// действия. С 26.09.2026 сервер работает дома круглосуточно (Linux, сам
/// запускается) — окно на компьютере больше ни при чём; причина почти всегда в
/// том, что телефон не дома и удалённый доступ выключен, или дома нет интернета.
const String kServerUnreachableHint =
    'Телефон не видит дом. Дома — проверьте Wi-Fi; не дома — включите «Удалённый доступ».';

/// Показать плашку «нет связи с домом» с подсказкой.
/// [lead] — короткое пояснение, что именно не получилось (например, «Радио
/// не собралось»); без него — просто «Сервер не ответил».
void showServerUnreachable({String? lead}) {
  // Без кнопки (разбор Gemini 26.09.2026): кнопка наверху экрана за рулём не
  // достаётся, а «Проверить» есть в «Связи с домом» (в Профиле видно «Нет связи ●»).
  Notice.show(
    lead ?? 'Нет связи с домом',
    subtitle: kServerUnreachableHint,
    kind: NoticeKind.error,
    duration: const Duration(seconds: 5),
  );
}
